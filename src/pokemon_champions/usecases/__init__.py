"""조립 층 — 밖(DB · 파일 · 네트워크)을 만지며 조립한다.

    battle.py        계산기 진입점 셋 — power · bulk · one_hit
    team.py          스펙 검증 · 빌드
    roster.py        덱 여러 벌 (파일 저장)
    naming.py        한↔영 이름 해석
    usage.py         채용률을 DB 의 한국어와 잇기
    usage_source.py  채용률 원본 받아오기 + 캐시

이 폴더에 들어올 자격은 하나다 — conn 이나 파일이나 네트워크를 만질 것.
안 만지면 calc/ 로 간다. 판정이 시그니처만 보면 끝나야 한다.

── 왜 이 층이 필요한가 ──
  calc/damage.py 는 DB 를 안 본다. 그건 옳다 — 계산이 순수해야 실제
  게임과 대조할 수 있고 tests/ 에 박아둘 수 있다. 대신 "DB 에서 읽어
  계산에 넘길 모양으로 만드는 일" 을 누군가는 해야 하는데, 그 자리가
  없어서 어댑터가 각자 떠맡고 있었다.

  결과는 같은 결정이 세 벌:

    무보정 성격 "성실"     app.py · tools.py · 대조용 CLI
    SP 기본 [0] * 6       셋 다
    allow_mega=True       셋 다
    스펙 -> Pokemon        _side_pokemon · _build · build
    BattleContext 조립     셋 다

  하나를 고치면 나머지 둘은 조용히 갈린다.

── 돌려주는 것은 뷰가 아니다 ──
  Pokemon 객체와 DamageRange 를 그대로 들고 있는 값을 돌려준다. JSON 이
  아니다. 그래야 어댑터마다 다른 모양으로 펼 수 있다 — API 는 아이콘
  URL 과 랭크를, 도구는 ko_name 짝을, CLI 는 터미널 한 줄을 만든다.
  계산은 한 번, 모양은 셋이다.

── 이 층이 모르는 것 ──
  HTTP 상태코드 · Pydantic · 도구 JSON 스키마 · {"error": ...} 규약 ·
  아이콘 URL. 어느 하나라도 들어오면 이건 다시 어댑터다.

── 커넥션은 인자로 ──
  모든 함수가 conn 을 첫 인자로 받는다. 모듈에 들고 있으면 웹에서
  동시 요청이 같은 psycopg2 커넥션을 나눠 쓰게 된다. 참조 데이터 캐시는
  모듈에 둬도 되지만(같은 값이 들어가므로) 커넥션은 아니다.

  roster.py 만 conn 을 안 받는다. 덱은 DB 가 아니라 파일에 있다 —
  ETL 이 참조 데이터를 통째로 다시 만들 때 같이 날아가면 안 되기
  때문이다. 그래도 밖을 만지는 것은 같으므로 여기에 있다.

── 아직 없는 것: 상대 팀 ──
  team.py 와 모양이 거의 같아지되 다른 점이 두 가지다.

    1. 상대 스펙은 대부분 모른다. SP · 성격 · 도구는 추정값이고, 확정된
       것과 추정한 것을 구분해서 들고 있어야 한다. (최속/최둔 가정 등)
    2. 대전마다 새로 만들어지고 버려진다. 내 팀처럼 파일에 저장할 이유가
       없다.

  그래서 team.py 를 그대로 복사하지 말고, 공통 부분이 정말 생겼을 때
  뽑아내는 편이 낫다.

  예전에는 이 메모가 opponent.py 라는 빈 파일에 있었다. 코드가 0줄인
  파일은 목록에서 "있는 기능" 처럼 보여서 여기로 옮겼다.
"""
